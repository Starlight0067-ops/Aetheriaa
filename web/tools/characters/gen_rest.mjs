// Generates src/characters/rest_unreal.js: canonical rest rotations for the Unreal-style animation rig.
// The Unreal FBX files store frame 0 of each clip as their node "rest", so we take one neutral standing
// frame (idle.fbx, frame 0) as the shared reference for every Unreal-rig clip.
import fs from 'node:fs';
import { loadFBX } from './fbx_node.mjs';
const a = loadFBX('assets_src/mixamo/idle.fbx');
const rest = {};
a.traverse((o) => { if (o !== a && o.name) rest[o.name] = o.quaternion.toArray().map((v) => +v.toFixed(6)); });
fs.writeFileSync('src/characters/rest_unreal.js', '// GENERATED by tools/characters/gen_rest.mjs (from assets_src/mixamo/idle.fbx frame 0). Do not edit.\nexport const UNREAL_REST = ' + JSON.stringify(rest) + ';\n');
console.log('bones', Object.keys(rest).length);
